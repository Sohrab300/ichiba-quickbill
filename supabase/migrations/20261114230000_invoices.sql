  'Returns one invoice in the create_invoice() JSON shape, or NULL. service_role only; callers check access.';

-- ---------------------------------------------------------------------------
-- 8. Row Level Security and privileges
-- ---------------------------------------------------------------------------
alter table public.invoice_sequences enable row level security;
alter table public.invoices          enable row level security;
alter table public.invoice_items     enable row level security;
-- No policies: anon/authenticated get nothing. The service role bypasses RLS but has only the
-- privileges granted below.

revoke all on table public.invoice_sequences, public.invoices, public.invoice_items
  from public, anon, authenticated, service_role;
-- Read access for reprint/history/exports. No INSERT/UPDATE/DELETE/TRUNCATE for any API role:
-- invoices are written only through create_invoice() (which runs as the owner).
grant select on table public.invoices, public.invoice_items to service_role;

revoke all on function public.create_invoice(uuid, uuid, uuid, jsonb, text) from public, anon, authenticated;
grant execute on function public.create_invoice(uuid, uuid, uuid, jsonb, text) to service_role;

revoke all on function public.get_invoice(uuid) from public, anon, authenticated;
grant execute on function public.get_invoice(uuid) to service_role;

-- Internal helpers: not callable through the API at all.
revoke all on function public.invoice_json(uuid) from public, anon, authenticated, service_role;
revoke all on function public.invoices_immutable() from public, anon, authenticated, service_role;
revoke all on function public.invoice_sequences_guard() from public, anon, authenticated, service_role;
