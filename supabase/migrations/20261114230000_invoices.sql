create table public.invoice_items (
  id            uuid primary key default gen_random_uuid(),
  invoice_id    uuid not null references public.invoices (id) on delete restrict,
  line_no       smallint not null constraint invoice_items_line_no_pos check (line_no >= 1),
  -- RESTRICT: a product that has been sold cannot be deleted (deactivate it instead).
  product_id    uuid not null references public.products (id) on delete restrict,
  -- Snapshot of the product at the time of sale.
  item_code     text not null,
  name          text not null,
  hsn_code      text null,
  uom           text not null,
  unit_price    integer not null constraint invoice_items_unit_price_nonneg check (unit_price >= 0),
  mrp           integer null,
  gst_rate      smallint not null constraint invoice_items_gst_rate_range check (gst_rate between 0 and 100),
  qty           integer not null constraint invoice_items_qty_range check (qty between 1 and 9999),
  line_total    bigint not null,
  taxable_value bigint not null constraint invoice_items_taxable_nonneg check (taxable_value >= 0),
  cgst          bigint not null constraint invoice_items_cgst_nonneg check (cgst >= 0),
  sgst          bigint not null,
  constraint invoice_items_invoice_line_key unique (invoice_id, line_no),
  constraint invoice_items_line_total check (line_total = unit_price::bigint * qty),
  constraint invoice_items_tax_adds_up check (taxable_value + cgst + sgst = line_total),
  constraint invoice_items_gst_split check (sgst - cgst in (0, 1))
);

comment on table public.invoice_items is
  'Invoice lines with product, price and GST snapshots. Immutable; written only by create_invoice().';

create index invoice_items_product_id_idx on public.invoice_items (product_id);

