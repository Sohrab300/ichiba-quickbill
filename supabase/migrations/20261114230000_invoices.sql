-- Migration: invoices, invoice numbering, GST and idempotent sale creation
-- (REQUIREMENTS.md sections 3, 5 and 6)
--
-- * invoice_sequences: one row per (counter, FY). The row lock taken by
--   INSERT … ON CONFLICT DO UPDATE serializes number assignment per counter; because it happens
--   inside the invoice's own transaction, a rolled-back sale never burns a number, and counters
--   never wait for each other.
-- * invoices / invoice_items: immutable snapshots (prices, GST, store header, cashier name), so an
--   old invoice reprints unchanged after products or settings change. API roles can only SELECT;
--   rows are written only by create_invoice(); a trigger refuses UPDATE / DELETE / TRUNCATE for
--   everyone, including the table owner (dashboard SQL editor).
-- * create_invoice(): SECURITY DEFINER, EXECUTE for service_role only. Idempotent on
--   p_idempotency_key, including when two requests with the same key arrive at the same time.
-- * get_invoice(): the same JSON shape, for reprint.
--
-- Money is integer paise throughout. Line and invoice totals are bigint so large bills cannot
-- overflow; unit prices stay integer like products.selling_price.

-- ---------------------------------------------------------------------------
-- 1. invoice_sequences
-- ---------------------------------------------------------------------------
create table public.invoice_sequences (
  counter_id  uuid not null references public.counters (id) on delete restrict,
  fy          text not null
              constraint invoice_sequences_fy_format check (fy ~ '^[0-9]{2}-[0-9]{2}$'),
  last_number integer not null
              constraint invoice_sequences_last_number_nonneg check (last_number >= 0),
  updated_at  timestamptz not null default now(),
  primary key (counter_id, fy)
);

comment on table public.invoice_sequences is
  'Last issued invoice number per counter and FY. Only create_invoice() writes it; it can only move forward.';

-- Numbers are never reused: refuse deletes, truncates and decreases (an increase, e.g. to continue
-- an older paper series, is allowed for the table owner).
create function public.invoice_sequences_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op in ('DELETE', 'TRUNCATE') then
    raise exception 'Invoice sequences cannot be deleted: invoice numbers are never reused.';
  end if;
  if new.counter_id <> old.counter_id or new.fy <> old.fy or new.last_number < old.last_number then
    raise exception 'Invoice sequences can only move forward (counter %, FY %: % -> %).',
      old.counter_id, old.fy, old.last_number, new.last_number;
  end if;
  return new;
end;
$$;

create trigger invoice_sequences_guard_row
  before update or delete on public.invoice_sequences
  for each row execute function public.invoice_sequences_guard();
create trigger invoice_sequences_guard_truncate
  before truncate on public.invoice_sequences
  for each statement execute function public.invoice_sequences_guard();

-- ---------------------------------------------------------------------------
-- 2. invoices
-- ---------------------------------------------------------------------------
create table public.invoices (
  id               uuid primary key default gen_random_uuid(),
  -- {PREFIX}/{FY}/{6-digit seq}, e.g. CL1/26-27/000001. Unique across all counters.
  invoice_no       text not null constraint invoices_invoice_no_key unique,
  counter_id       uuid not null references public.counters (id) on delete restrict,
  counter_code     text not null,
  fy               text not null
                   constraint invoices_fy_format check (fy ~ '^[0-9]{2}-[0-9]{2}$'),
  seq_number       integer not null
                   constraint invoices_seq_number_range check (seq_number between 1 and 999999),
  -- Generated by the browser per cart; a retry with the same key returns this invoice.
  idempotency_key  uuid not null constraint invoices_idempotency_key_key unique,
  -- No FK to auth.users: an invoice must outlive the login that issued it. Name is snapshotted.
  cashier_user_id  uuid not null,
  cashier_name     text not null,
  payment_method   text not null
                   constraint invoices_payment_method_valid check (payment_method in ('cash', 'upi', 'card')),
  item_count       integer not null constraint invoices_item_count_pos check (item_count >= 1),
  total_qty        integer not null constraint invoices_total_qty_pos check (total_qty >= 1),
  subtotal         bigint not null constraint invoices_subtotal_nonneg check (subtotal >= 0),
  taxable_total    bigint not null constraint invoices_taxable_nonneg check (taxable_total >= 0),
  cgst_total       bigint not null constraint invoices_cgst_nonneg check (cgst_total >= 0),
  sgst_total       bigint not null constraint invoices_sgst_nonneg check (sgst_total >= 0),
  round_off        integer not null constraint invoices_round_off_range check (round_off between -49 and 50),
  grand_total      bigint not null,
  -- Store header as it was when the invoice was issued.
  store_legal_name text not null,
  store_address    text not null,
  store_phone      text null,
  store_gstin      text not null,
  store_state_code text not null,
  store_state_name text not null,
  invoice_footer   text null,
  created_at       timestamptz not null default now(),
  constraint invoices_counter_fy_seq_key unique (counter_id, fy, seq_number),
  constraint invoices_invoice_no_format
    check (invoice_no ~ ('^[A-Z0-9]{1,8}/' || fy || '/' || lpad(seq_number::text, 6, '0') || '$')),
  constraint invoices_totals_add_up check (subtotal = taxable_total + cgst_total + sgst_total),
  constraint invoices_grand_total_rounded check (grand_total = subtotal + round_off and grand_total % 100 = 0)
);

comment on table public.invoices is
  'Issued tax invoices. Immutable; written only by create_invoice(). Amounts in paise.';

create index invoices_created_at_idx on public.invoices (created_at desc);
create index invoices_counter_created_at_idx on public.invoices (counter_id, created_at desc);

